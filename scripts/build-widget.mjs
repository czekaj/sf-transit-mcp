import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const generated = new URL("../src/generated/", import.meta.url);
await mkdir(generated, { recursive: true });
const icon = await readFile(new URL("../assets/icon-256.png", import.meta.url));
const listingIcon = await readFile(
  new URL("../assets/icon-512.png", import.meta.url),
);
const iconSource = `data:image/png;base64,${icon.toString("base64")}`;
await writeFile(
  new URL("branding.ts", generated),
  `// Generated from assets/icon-256.png and assets/icon-512.png by scripts/build-widget.mjs.\nexport const BRAND_ICON_SRC = ${JSON.stringify(iconSource)};\nexport const BRAND_ICONS = [{ src: BRAND_ICON_SRC, mimeType: "image/png", sizes: ["256x256"] }];\nexport const LISTING_ICON_BASE64 = ${JSON.stringify(listingIcon.toString("base64"))};\n`,
);
const result = await build({
  absWorkingDir: root,
  entryPoints: ["widget/app.ts"],
  bundle: true,
  platform: "browser",
  format: "iife",
  target: ["es2022"],
  minify: true,
  legalComments: "inline",
  metafile: true,
  write: false,
  define: { "process.env.NODE_ENV": '"production"' },
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const template = await readFile(
  new URL("../widget/index.html", import.meta.url),
  "utf8",
);
const css = await readFile(
  new URL("../widget/style.css", import.meta.url),
  "utf8",
);
const packages = [
  ...new Set(
    Object.keys(result.metafile.inputs)
      .filter((path) => path.startsWith("node_modules/"))
      .map((path) => {
        const parts = path.split("/");
        return parts.slice(1, parts[1].startsWith("@") ? 3 : 2).join("/");
      }),
  ),
].sort();
const notices = [];
for (const name of packages) {
  const directory = new URL(`../node_modules/${name}/`, import.meta.url);
  const files = (await readdir(directory))
    .filter((name) => /^(licen[sc]e|notice)(\..*)?$/i.test(name))
    .sort();
  if (!files.some((name) => /^licen[sc]e/i.test(name)))
    throw new Error(`Missing bundled license for ${name}`);
  for (const file of files)
    notices.push(
      `${name} — ${file}\n${await readFile(new URL(file, directory), "utf8")}`,
    );
}
for (const marker of ["<!-- APP_STYLE -->", "<!-- APP_SCRIPT -->"]) {
  if (template.split(marker).length !== 2)
    throw new Error(`Expected exactly one ${marker} placeholder`);
}
const html = template
  .replace("<!-- APP_STYLE -->", () => `<style>${css}</style>`)
  .replace(
    "<!-- APP_SCRIPT -->",
    () =>
      `<!-- Bundled third-party notices:\n${notices.join("\n\n").replaceAll("-->", "-- >")}\n-->\n<script>${script}</script>`,
  );
if (Buffer.byteLength(html) > 2 * 1024 * 1024)
  throw new Error("Widget exceeds its 2 MiB resource budget");
const hash = createHash("sha256").update(html).digest("hex").slice(0, 16);
const uri = `ui://sf-transit/itinerary-${hash}.html`;
await mkdir(new URL("../dist/", import.meta.url), { recursive: true });
await writeFile(
  new URL("widget.ts", generated),
  `// Generated by scripts/build-widget.mjs.\nexport const WIDGET_RESOURCE_URI = ${JSON.stringify(uri)};\nexport const WIDGET_HTML = ${JSON.stringify(html)};\n`,
);
await writeFile(new URL("../dist/widget.html", import.meta.url), html);
console.log(
  `Built itinerary widget (${Math.round(Buffer.byteLength(html) / 1024)} KiB, ${hash}).`,
);
